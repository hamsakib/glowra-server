/** Picks three distinct photos from a category pool, starting at a different offset per product. */
export function imagesFor(category, index) {
  const pool = pools[category];
  const n = pool.length;
  return [pool[index % n], pool[(index + 4) % n], pool[(index + 7) % n]].map((id) => img(id));
}

